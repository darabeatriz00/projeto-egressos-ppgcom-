def explodir_multirrotulo(df, coluna, nome_novo):
    linhas = []
    for _, row in df.iterrows():
        valor = str(row.get(coluna, '') or '')
        for item in valor.split(';'):
            item = item.strip()
            if item:
                linhas.append({
                    'ID_ENTIDADE': row.get('ID_ENTIDADE', ''),
                    nome_novo: item,
                    'ANO': row.get('ANO', ''),
                    'TITULO': row.get('TITULO', '')
                })
    return pd.DataFrame(linhas)

