SALVAR_A_CADA = 50

ARQ_CKPT_AREAS = PASTA_SAIDA / 'checkpoint_areas.json'
ARQ_CKPT_ODS   = PASTA_SAIDA / 'checkpoint_ods.json'

def carregar_ckpt(arq):
    if arq.exists():
        with open(arq, 'r', encoding='utf-8') as f:
            return json.load(f)
    return {}

def salvar_ckpt(arq, d):
    with open(arq, 'w', encoding='utf-8') as f:
        json.dump(d, f, ensure_ascii=False)

def classificar_zeroshot(textos, labels, template, ckpt_arq,
                         batch_size=BATCH_SIZE, multi_label=True):
    cache = carregar_ckpt(ckpt_arq)
    resultados = [None] * len(textos)

    for i, txt in enumerate(textos):
        chave = str(hash((str(txt)[:200], template)))
        if chave in cache:
            resultados[i] = cache[chave]

    pendentes = [i for i, r in enumerate(resultados) if r is None]
    print(f'  → {len(textos)} textos | cache: {len(textos)-len(pendentes)} | pendentes: {len(pendentes)}')
    barra = tqdm(total=len(pendentes), desc='Classificando')

    for inicio in range(0, len(pendentes), batch_size):
        lote_idx = pendentes[inicio:inicio + batch_size]
        lote_txt = [str(textos[i])[:1000] for i in lote_idx]
        saida = classificador(lote_txt, labels, multi_label=multi_label,
                              hypothesis_template=template, truncation=True)
        if isinstance(saida, dict):
            saida = [saida]
        for i, r in zip(lote_idx, saida):
            resultados[i] = r
            cache[str(hash((str(textos[i])[:200], template)))] = r
        barra.update(len(lote_idx))
        if inicio > 0 and (inicio // batch_size) % (SALVAR_A_CADA // batch_size) == 0:
            salvar_ckpt(ckpt_arq, cache)

    barra.close()
    salvar_ckpt(ckpt_arq, cache)
    return resultados

