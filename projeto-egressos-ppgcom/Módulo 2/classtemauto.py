def moda_texto(serie):
    v = serie.dropna().astype(str)
    v = v[v.str.strip() != '']
    return v.mode().iloc[0] if not v.empty else ''

def primeiro_texto(serie):
    v = [str(x).strip() for x in serie if str(x).strip()]
    return v[0] if v else ''

def unir_textos(serie):
    itens = set()
    for valor in serie:
        if pd.isna(valor): continue
        for p in str(valor).split(';'):
            p = p.strip()
            if p: itens.add(p)
    return '; '.join(sorted(itens))

def titulos_exemplo(serie, n=10):
    vistos = []
    for v in serie:
        v = str(v).strip()
        if v and v not in vistos: vistos.append(v)
        if len(vistos) >= n: break
    return ' | '.join(vistos)

def formatar_periodo(row):
    a, b = row['ANO_MIN'], row['ANO_MAX']
    if pd.isna(a) and pd.isna(b): return ''
    a_str = str(int(a)) if pd.notna(a) else ''
    b_str = str(int(b)) if pd.notna(b) else ''
    return f'{a_str}–{b_str}'.strip('–')

