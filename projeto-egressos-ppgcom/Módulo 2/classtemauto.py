N_POR_ESTRATO = 25

def amostra_estratificada(df):
    if df.empty:
        return df.copy()
    partes = []
    partes.append(df[(df['CONF_MODELO_AREA'] == 'alta') &
                     (df['CONF_MODELO_ODS']  == 'alta')].head(N_POR_ESTRATO))
    partes.append(df[(df['CONF_MODELO_AREA'] == 'baixa') |
                     (df['CONF_MODELO_ODS']  == 'baixa')].head(N_POR_ESTRATO))
    partes.append(df[df['CONCORDANCIA_ODS'] == 'divergem'].head(N_POR_ESTRATO))
    partes.append(df[df['CONCORDANCIA_REGRA'] == 'contraria'].head(N_POR_ESTRATO))
    partes.append(df.sample(min(N_POR_ESTRATO, len(df)), random_state=42))
    return (pd.concat(partes)
              .drop_duplicates(subset=['TITULO'])
              .reset_index(drop=True))

