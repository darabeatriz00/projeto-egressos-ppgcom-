def classificar_zeroshot(textos, labels, template, batch_size=8, multi_label=True):
    saidas = []

    for i in range(0, len(textos), batch_size):
        lote = [str(t)[:1000] for t in textos[i:i+batch_size]]

        if not lote:
            continue

        saida = classificador(
            lote,
            labels,
            multi_label=multi_label,
            hypothesis_template=template,
            truncation=True
        )

        if isinstance(saida, dict):
            saida = [saida]

        saidas.extend(saida)

    return saidas

