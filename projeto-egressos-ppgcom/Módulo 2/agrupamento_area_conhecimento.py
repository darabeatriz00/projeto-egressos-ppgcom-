def limpar_valor(valor):
    if pd.isna(valor):
        return ''
    return str(valor).strip()

def remover_acentos(texto):
    texto = unicodedata.normalize('NFKD', texto)
    return ''.join(c for c in texto if not unicodedata.combining(c))

def normalizar_texto(valor):
    valor = limpar_valor(valor)
    if not valor:
        return ''
    valor = remover_acentos(valor)
    valor = valor.lower()
    valor = re.sub(r'[^a-z0-9\s]', ' ', valor)
    valor = re.sub(r'\s+', ' ', valor)
    return valor.strip()

def normalizar_lattes(valor):
    valor = limpar_valor(valor)
    return re.sub(r'\D', '', valor)

def normalizar_orcid(valor):
    valor = limpar_valor(valor)
    if not valor:
        return ''

    valor = re.sub(r'^https?://orcid\.org/', '', valor, flags=re.IGNORECASE)
    valor = re.sub(r'^orcid:\s*', '', valor, flags=re.IGNORECASE)
    valor = re.sub(r'\s+', '', valor)

    # Se vier sem hífens e tiver 16 caracteres, formata
    if len(valor) == 16 and valor.count('-') == 0:
        valor = '-'.join([valor[i:i+4] for i in range(0, 16, 4)])

    return valor.strip()

def normalizar_doi(valor):
    valor = limpar_valor(valor).lower()
    for prefixo in ['https://doi.org/', 'http://doi.org/', 'doi:']:
        valor = valor.replace(prefixo, '')
    return valor.strip().rstrip('/')

def localizar_coluna(df, alternativas):
    """
    Localiza colunas por nomes aproximados.
    """
    mapa = {normalizar_texto(c): c for c in df.columns}
    for alternativa in alternativas:
        chave = normalizar_texto(alternativa)
        if chave in mapa:
            return mapa[chave]
    return None

def combinar_campos_texto(df, colunas):
    """
    Combina várias colunas em uma única coluna textual.
    """
    if not colunas:
        return pd.Series([''] * len(df))

    def juntar(linha):
        valores = []
        for v in linha:
            v = str(v).strip()
            if v:
                valores.append(v)
        return '; '.join(dict.fromkeys(valores))

    return df[colunas].fillna('').apply(juntar, axis=1)

