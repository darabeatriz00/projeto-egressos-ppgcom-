def api_get_json(url, params=None, headers=None, timeout=45, tentativas=3):
    """
    Faz requisições com retry simples.
    """
    for tentativa in range(tentativas):
        try:
            resposta = requests.get(url, params=params, headers=headers, timeout=timeout)

            if resposta.status_code == 200:
                return resposta.json()

            if resposta.status_code in (429, 500, 502, 503, 504):
                time.sleep(2 * (tentativa + 1))
                continue

            return None

        except Exception:
            time.sleep(2 * (tentativa + 1))

    return None

def limpar_jats(texto):
    """
    Remove tags XML/JATS de resumos do Crossref.
    """
    if not texto:
        return ''
    texto = re.sub(r'<[^>]+>', ' ', str(texto))
    texto = re.sub(r'\s+', ' ', texto)
    return texto.strip()

def reconstruir_abstract_openalex(inverted_index):
    """
    O OpenAlex pode devolver resumo como índice invertido.
    Ex.: {'saúde': [0,5], 'pública': [1]}
    """
    if not inverted_index:
        return ''

    pares = []
    for palavra, posicoes in inverted_index.items():
        for pos in posicoes:
            pares.append((pos, palavra))

    pares.sort(key=lambda x: x[0])
    return ' '.join(palavra for _, palavra in pares)

def parse_openalex_work(work):
    """
    Converte um trabalho do OpenAlex em linha padronizada.
    """
    titulo = (work.get('title') or '').strip()
    doi = (work.get('doi') or '').strip()
    doi = doi.replace('https://doi.org/', '').replace('http://doi.org/', '')
    ano = work.get('publication_year', '')

    resumo = reconstruir_abstract_openalex(work.get('abstract_inverted_index'))

    temas = []

    # Topics
    for topic in (work.get('topics') or [])[:8]:
        if not isinstance(topic, dict):
            continue
        temas.append(topic.get('display_name', ''))
        temas.append((topic.get('subfield') or {}).get('display_name', ''))
        temas.append((topic.get('field') or {}).get('display_name', ''))
        temas.append((topic.get('domain') or {}).get('display_name', ''))

    # Concepts
    for concept in (work.get('concepts') or [])[:12]:
        if isinstance(concept, dict):
            temas.append(concept.get('display_name', ''))

    # Keywords
    for keyword in (work.get('keywords') or [])[:8]:
        if isinstance(keyword, dict):
            temas.append(keyword.get('display_name', ''))
        else:
            temas.append(str(keyword))

    temas = list(dict.fromkeys([t for t in temas if t]))[:50]

    # Periódico/fonte
    periodico = ''
    primary_location = work.get('primary_location') or {}
    source = primary_location.get('source') or {}
    if isinstance(source, dict):
        periodico = source.get('display_name', '')

    # ODS
    ods = []
    for goal in (work.get('sustainable_development_goals') or []):
        if not isinstance(goal, dict):
            continue

        url_goal = goal.get('id', '') or ''
        nome_goal = goal.get('display_name', '') or ''
        codigo = None

        m = re.search(r'/(\d+)$', url_goal)
        if m:
            codigo = m.group(1)

        if codigo and codigo.isdigit():
            nome_pt = ODS_MAPA.get(int(codigo), nome_goal)
            ods.append(f'{codigo} {nome_pt}'.strip())
        elif nome_goal:
            ods.append(nome_goal)

    ods = list(dict.fromkeys([o for o in ods if o]))

    return {
        'TITULO': titulo,
        'DOI': doi,
        'ANO': str(ano) if ano else '',
        'RESUMO': resumo,
        'TEMAS': '; '.join(temas),
        'PERIODICO': periodico,
        'ODS_OPENALEX': '; '.join(ods),
        'FONTE': 'OpenAlex API'
    }

def parse_crossref_item(item):
    """
    Converte um trabalho do Crossref em linha padronizada.
    """
    titulo = item.get('title', '')
    if isinstance(titulo, list):
        titulo = titulo[0] if titulo else ''
    titulo = str(titulo).strip()

    doi = item.get('DOI', '') or ''

    resumo = limpar_jats(item.get('abstract', ''))

    assuntos = item.get('subject', []) or []
    if isinstance(assuntos, str):
        assuntos = [assuntos]
    assuntos = [str(a).strip() for a in assuntos if str(a).strip()]

    periodico = item.get('container-title', '')
    if isinstance(periodico, list):
        periodico = periodico[0] if periodico else ''
    periodico = str(periodico).strip()

    issued = item.get('issued', {}) or {}
    date_parts = issued.get('date-parts', [[None]])
    ano = ''
    if date_parts and len(date_parts) > 0 and len(date_parts[0]) > 0:
        ano = date_parts[0][0] or ''

    return {
        'TITULO': titulo,
        'DOI': doi,
        'ANO': str(ano) if ano else '',
        'RESUMO': resumo,
        'TEMAS': '; '.join(dict.fromkeys(assuntos)),
        'PERIODICO': periodico,
        'ODS_OPENALEX': '',
        'FONTE': 'Crossref API'
    }

def openalex_por_orcid(orcid, max_works=100):
    """
    Busca produções no OpenAlex usando ORCID do autor.
    """
    if not orcid:
        return []

    producoes = []
    pagina = 1

    while len(producoes) < max_works:
        params = {
            'filter': f'author.orcid:{orcid}',
            'per-page': 100,
            'page': pagina,
            'mailto': EMAIL_POLITE
        }

        dados = api_get_json('https://api.openalex.org/works', params=params)
        if not dados:
            break

        resultados = dados.get('results', [])
        if not resultados:
            break

        for work in resultados:
            producoes.append(parse_openalex_work(work))
            if len(producoes) >= max_works:
                break

        if len(resultados) < 100:
            break

        pagina += 1
        time.sleep(0.4)

    return producoes

def crossref_por_orcid(orcid, max_works=100):
    """
    Busca produções no Crossref usando ORCID do autor.
    """
    if not orcid:
        return []

    headers = {
        'User-Agent': f'RAGI-UFG/1.0 (mailto:{EMAIL_POLITE})'
    }

    producoes = []
    offset = 0
    rows = 100

    while len(producoes) < max_works:
        params = {
            'filter': f'orcid:{orcid}',
            'rows': rows,
            'offset': offset,
            'select': 'DOI,title,abstract,subject,container-title,issued'
        }

        dados = api_get_json('https://api.crossref.org/works', params=params, headers=headers)

        if not dados or 'message' not in dados:
            break

        itens = dados['message'].get('items', [])
        if not itens:
            break

        for item in itens:
            producoes.append(parse_crossref_item(item))
            if len(producoes) >= max_works:
                break

        if len(itens) < rows:
            break

        offset += rows
        time.sleep(0.5)

    return producoes

def melhor_candidato(candidatos, titulo):
    """
    Escolhe o melhor resultado de busca por título.
    Só aceita se a similaridade for alta.
    """
    if not candidatos or not titulo:
        return None

    titulo_norm = normalizar_texto(titulo)
    melhor = None
    melhor_score = 0

    for candidato in candidatos:
        titulo_candidato = candidato.get('TITULO', '')
        titulo_candidato_norm = normalizar_texto(titulo_candidato)

        if not titulo_candidato_norm:
            continue

        score = fuzz.token_set_ratio(titulo_norm, titulo_candidato_norm)

        if score > melhor_score:
            melhor_score = score
            melhor = candidato

    if melhor_score >= 92:
        return melhor

    return None

def openalex_por_doi(doi):
    """
    Busca metadados no OpenAlex usando DOI.
    """
    if not doi:
        return None

    url = f'https://api.openalex.org/works/doi:{quote(doi, safe="")}'
    dados = api_get_json(url, params={'mailto': EMAIL_POLITE})

    if dados and isinstance(dados, dict) and dados.get('title'):
        return parse_openalex_work(dados)

    return None

def crossref_por_doi(doi):
    """
    Busca metadados no Crossref usando DOI.
    """
    if not doi:
        return None

    url = f'https://api.crossref.org/works/{quote(doi, safe="")}'
    headers = {
        'User-Agent': f'RAGI-UFG/1.0 (mailto:{EMAIL_POLITE})'
    }

    dados = api_get_json(url, headers=headers)

    if dados and 'message' in dados:
        return parse_crossref_item(dados['message'])

    return None

def openalex_por_titulo(titulo, top=5):
    """
    Busca produção no OpenAlex usando título.
    """
    if not titulo:
        return None

    params = {
        'search': titulo,
        'per-page': top,
        'mailto': EMAIL_POLITE
    }

    dados = api_get_json('https://api.openalex.org/works', params=params)
    if not dados:
        return None

    resultados = dados.get('results', [])
    candidatos = [parse_openalex_work(w) for w in resultados]

    return melhor_candidato(candidatos, titulo)

def crossref_por_titulo(titulo, top=5):
    """
    Busca produção no Crossref usando título.
    """
    if not titulo:
        return None

    headers = {
        'User-Agent': f'RAGI-UFG/1.0 (mailto:{EMAIL_POLITE})'
    }

    params = {
        'query.bibliographic': titulo,
        'rows': top,
        'select': 'DOI,title,abstract,subject,container-title,issued'
    }

    dados = api_get_json('https://api.crossref.org/works', params=params, headers=headers)

    if not dados or 'message' not in dados:
        return None

    itens = dados['message'].get('items', [])
    candidatos = [parse_crossref_item(item) for item in itens]

    return melhor_candidato(candidatos, titulo)

