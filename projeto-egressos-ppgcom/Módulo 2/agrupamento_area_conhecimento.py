def moda_texto(serie):
    valores = serie.dropna().astype(str)
    valores = valores[valores.str.strip() != '']
    if valores.empty:
        return ''
    return valores.mode().iloc[0]

def primeiro_texto(serie):
    valores = [str(v).strip() for v in serie if str(v).strip() != '']
    return valores[0] if valores else ''

def unir_textos(serie):
    itens = set()
    for valor in serie:
        if pd.isna(valor):
            continue
        for parte in str(valor).split(';'):
            parte = parte.strip()
            if parte:
                itens.add(parte)
    return '; '.join(sorted(itens))

def titulos_exemplo(serie, n=10):
    vistos = []
    for valor in serie:
        valor = str(valor).strip()
        if valor and valor not in vistos:
            vistos.append(valor)
        if len(vistos) >= n:
            break
    return ' | '.join(vistos)

if not df_classificacao.empty:
    df_por_entidade = df_classificacao[
        df_classificacao['ID_ENTIDADE'].astype(str).str.strip() != ''
    ].copy()
else:
    df_por_entidade = pd.DataFrame()

if not df_por_entidade.empty:
    classificacao_egressos = df_por_entidade.groupby('ID_ENTIDADE').agg(
        NOME_CANONICO=('NOME_CANONICO', primeiro_texto),
        TOTAL_PUBLICACOES=('TITULO', 'count'),
        AREA_PREDOMINANTE=('AREA_FINAL', moda_texto),
        ODS_PREDOMINANTE=('ODS_FINAL', moda_texto),
        ODS_TODOS=('ODS_ADERENTES', unir_textos),
        TITULOS_EXEMPLO=('TITULO', lambda x: titulos_exemplo(x, 10))
    ).reset_index()
else:
    classificacao_egressos = pd.DataFrame(columns=[
        'ID_ENTIDADE',
        'NOME_CANONICO',
        'TOTAL_PUBLICACOES',
        'AREA_PREDOMINANTE',
        'ODS_PREDOMINANTE',
        'ODS_TODOS',
        'TITULOS_EXEMPLO'
    ])

